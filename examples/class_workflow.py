"""Run a two-timepoint TubULAR workflow without writing files.

Run: python examples/class_workflow.py
The surface chart is supplied analytically, not generated by a mapping port.
"""

import numpy as np

from tubular import TubULAR
from tubular.grid import cylinder_mesh


def run():
    tubi = TubULAR(time_points=[0, 2], opts={"timeInterval": 3, "timeUnits": "min"})
    z, y, x = np.indices((25, 25, 33))
    for timepoint in tubi.timePoints:
        mesh = cylinder_mesh(17, 65, radius=6 + 0.25*timepoint, length=24, length_unit="um")
        mesh = mesh.with_vertices(mesh.v + [4, 12, 12])
        tubi.register_mesh(timepoint, mesh, kind="spcutMeshSm")
        # Mesh XYZ and volume coordinates share the same frame, with 1 um voxels.
        tubi.register_data(timepoint, 100 + 40*np.sin(x*np.pi/6) + 2*y + z + timepoint)

    for timepoint in tubi.timePoints:
        tubi.setTime(timepoint)
        mesh = tubi.getCurrentSPCutMeshSm()
        metric, curvature = tubi.measure_current_geometry()
        result = tubi.sample_current_pullback(np.linspace(0, 24, 49), np.linspace(0, 2*np.pi, 65))
        _, label = tubi.trueTime(timepoint, return_label=True)
        print(f"{label}: {len(mesh.v)} vertices; metric {metric.shape}; "
              f"curvature {curvature.shape}; pullback {result.image.shape}; "
              f"{np.count_nonzero(result.valid)}/{result.valid.size} valid samples")

    series = tubi.measureSurfaceAreaVolume({"mesh_kind": "spcutMeshSm", "allow_open": True})
    print("Surface area (um^2):", series["area"])
    print("Volume:", series["volume"], "(open cylinders do not enclose a volume)")
    print("Implemented MATLAB method names:", len(tubi.available_methods()))
    print("measureStrainRate status:", tubi.method_status("measureStrainRate")["status"])
    return tubi


if __name__ == "__main__":
    run()
